// Генератор ParameterCheck[] из ParamDef[]
export function createParameterChecks(defs: ParamDef[], allYes = true): ParameterCheck[] {
  return defs.map(d => ({
    id: d.id,
    name: d.name,
    level: d.level,
    assessment: allYes ? 'Да' : (Math.random() > 0.2 ? 'Да' : 'Нет'),
    correction: allYes ? 'Да' : null,
    comment: '',
    autoComment: '',
  }));
}
